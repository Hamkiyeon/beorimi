def get_recycling_info(class_name: str, is_dirty: bool) -> dict | None:
    guide = GUIDE_DATA.get(class_name)
    if not guide:
        return None

    steps = [s.strip() for s in guide["guide_text"].split("\n") if s.strip()]

    return {
        "class_name": class_name,
        "korean_name": guide["title"],
        "icon": guide.get("icon", "♻️"),
        "bin_color": guide["bin_color"],
        "disposal_steps": steps,
        "notes": None,
        "dirty_warning": "오염된 경우 세척 후 배출하거나 일반쓰레기로 처리해야 할 수 있습니다." if is_dirty else None,
    }


def get_all_categories() -> list[dict]:
    return [
        {"class_name": k, "korean_name": v["title"], "icon": v.get("icon", "♻️")}
        for k, v in GUIDE_DATA.items()
    ]
